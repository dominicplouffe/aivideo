export interface IdentifiedAccount {
  /** The email domain, which is the closest thing to a company we hold. */
  domain: string;
  viewers: number;
  /** Deepest fraction of any asset any of them watched. */
  maxDepth: number;
  lastSeenAt: string | null;
}

/**
 * Accounts that identified themselves, grouped by email domain.
 *
 * The analytics page rendered a five-row literal here — cardinal.com,
 * northwind.io, halcyon.security, tessera.dev, arcwell.health, each with a
 * viewer count, a watch depth and a pipeline "stage". None of it came from
 * anywhere, and the stage column described a CRM field this product never
 * read. Stage is gone; the rest is counted.
 *
 * Erased contacts keep their sessions and lose their name, so honouring a
 * deletion request does not restate the totals — see `lib/analytics/identity.ts`.
 */
export async function getIdentifiedAccounts(days = 30): Promise<IdentifiedAccount[]> {
  const { allowed: may, actor } = await guard("analytics.view");
  if (!may || !actor || !isDatabaseConfigured()) return [];

  try {
    const { getDb } = await import("@/lib/db/client");
    const { sql } = await import("drizzle-orm");
    const since = new Date(Date.now() - days * 24 * 60 * 60 * 1000);

    const rows = await getDb().execute(sql`
      SELECT split_part(c.email, '@', 2)               AS domain,
             count(DISTINCT c.id)::int                 AS viewers,
             max(s.watched_seconds::float
                 / nullif(s.asset_seconds, 0))         AS max_depth,
             max(s.started_at)                         AS last_seen_at
        FROM analytics_sessions s
        JOIN contacts c ON c.id = s.contact_id
       WHERE s.workspace_id = ${actor.workspaceId}::uuid
         AND s.started_at >= ${since.toISOString()}::timestamptz
         -- An erased contact has no address left to group by, and inventing
         -- a domain for one would undo the erasure on this very screen.
         AND c.erased_at IS NULL
         AND c.email <> ''
       GROUP BY 1
       ORDER BY viewers DESC, max_depth DESC
       LIMIT 20;
    `);

    return (rows as unknown as {
      domain: string;
      viewers: number;
      max_depth: number | null;
      last_seen_at: Date | string | null;
    }[]).map((row) => ({
      domain: row.domain,
      viewers: Number(row.viewers),
      maxDepth: Math.min(1, Number(row.max_depth ?? 0)),
      lastSeenAt: row.last_seen_at ? new Date(row.last_seen_at).toISOString() : null,
    }));
  } catch (error) {
    console.error("[data] identified accounts read failed:", error);
    return [];
  }
}

